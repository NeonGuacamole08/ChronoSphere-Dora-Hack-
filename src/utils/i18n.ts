const LANGUAGE_STORAGE_KEY = 'chronospheres_preferred_language_v2';

export function getStoredLanguage(): SupportedLanguage | null {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY) as SupportedLanguage | null;
    if (stored && LANGUAGES.some((l) => l.code === stored)) {
      return stored;
    }
  } catch {
    // fallback
  }
  return null;
}

export function setStoredLanguage(lang: SupportedLanguage): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    if (i18n && typeof i18n.changeLanguage === 'function') {
      i18n.changeLanguage(lang);
    }
  } catch {
    // ignore
  }
}

export function hasSelectedInitialLanguage(): boolean {
  return Boolean(getStoredLanguage());
}

export function translate(
  key: string,
  lang: SupportedLanguage = 'en',
  params?: Record<string, string | number>
): string {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dictionary[key] || TRANSLATIONS.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`{{\\s*${k}\\s*}}`, 'g'), String(v));
    });
  }
  return text;
}

// Build i18next resources structure
const i18nResources: Record<string, { translation: Record<string, string> }> = {};
Object.entries(TRANSLATIONS).forEach(([langKey, dict]) => {
  i18nResources[langKey] = {
    translation: dict,
  };
});

const initialLang = getStoredLanguage() || 'en';

i18n.use(initReactI18next).init({
  resources: i18nResources,
  lng: initialLang,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false, // React already safeguards against XSS
  },
});

export default i18n;
