/**
 * High-precision point-in-polygon algorithm to match coordinates to exact country
 */
export function matchCoordinatesToCountry(lat: number, lng: number): { countryCode: string; countryName: string } | null {
  // 1. Antarctica check (Latitudes south of -60°)
  if (lat <= -60) {
    return { countryCode: 'AQ', countryName: 'Antarctica' };
  }

  // 2. Loop through boundary polygons
  for (const b of WORLD_COUNTRY_BORDERS) {
    const poly = b.coordinates;
    let inside = false;

    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [yi, xi] = poly[i];
      const [yj, xj] = poly[j];

      const intersect =
        yi > lat !== yj > lat &&
        lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi;

      if (intersect) {
        inside = !inside;
      }
    }

    if (inside) {
      return { countryCode: b.cca2, countryName: b.name };
    }
  }

  return null;
}
